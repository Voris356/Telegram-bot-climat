def build_welcome(company_name: str, city: str = "", phone: str = "") -> str:
    """Собрать приветствие, не придумывая отсутствующие контакты или зону выезда."""
    name = company_name.strip() or "Сервис кондиционеров"
    lines = [
        f"Здравствуйте! Вы в чате «{name}».",
        "Помогаем с установкой, ремонтом, проверкой и заправкой кондиционеров, "
        "а также с профилактикой.",
    ]
    if city.strip():
        lines.append(f"Зона обслуживания: {city.strip()}.")
    if phone.strip():
        lines.append(f"Телефон для связи: {phone.strip()}.")
    lines.append("Выберите услугу или задайте вопрос в меню ниже.")
    return "\n\n".join(lines)
